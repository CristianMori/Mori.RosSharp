using Mori.RosSharp.Msg;

// rosmsggen: typed C# message classes from ROS 1 .msg files.
//
// Inputs are .msg files or directories laid out ROS-style (<package>/msg/<Name>.msg or
// <package>/<Name>.msg). Nested types resolve against the inputs first, then the embedded
// common-message set (std_msgs, geometry_msgs, sensor_msgs basics, nav_msgs, tf2_msgs), and the
// emitted set is closed over dependencies, so the output always compiles.
//
// Usage:
//   rosmsggen -o <outDir> [-n <rootNamespace>] [--package <name>] <files-or-dirs…>
// Options:
//   -o <dir>          output directory for the generated .cs files (required)
//   -n <namespace>    root namespace (default RosMessages); classes land in <ns>.<package>
//   --package <name>  package name for loose .msg files whose directory doesn't imply one

var inputs = new List<string>();
string? outDir = null, forcedPackage = null;
string ns = "RosMessages";

for (int i = 0; i < args.Length; i++)
{
    switch (args[i])
    {
        case "-o" when i + 1 < args.Length: outDir = args[++i]; break;
        case "-n" when i + 1 < args.Length: ns = args[++i]; break;
        case "--package" when i + 1 < args.Length: forcedPackage = args[++i]; break;
        default: inputs.Add(args[i]); break;
    }
}

if (outDir is null || inputs.Count == 0)
{
    Console.Error.WriteLine("usage: rosmsggen -o <outDir> [-n <rootNamespace>] [--package <name>] <files-or-dirs...>");
    return 1;
}

// Collect (fullType, text) from the inputs.
var sources = new Dictionary<string, string>();
foreach (string input in inputs)
{
    if (Directory.Exists(input))
    {
        foreach (string file in Directory.EnumerateFiles(input, "*.msg", SearchOption.AllDirectories))
            Add(file, PackageOf(file));
    }
    else if (File.Exists(input))
    {
        Add(input, forcedPackage ?? PackageOf(input));
    }
    else
    {
        Console.Error.WriteLine($"rosmsggen: no such file or directory: {input}");
        return 1;
    }
}

var catalog = new MsgCatalog(fullType => sources.GetValueOrDefault(fullType));

try
{
    Directory.CreateDirectory(outDir);
    List<KeyValuePair<string, string>> emitted =
        CSharpEmitter.EmitClosure(sources.Keys, catalog, ns, "generated by rosmsggen; do not edit");
    foreach ((string fullType, string code) in emitted)
    {
        string file = Path.Combine(outDir, fullType.Replace('/', '.') + ".g.cs");
        File.WriteAllText(file, code);
        Console.WriteLine($"  {fullType}  md5 {catalog.Md5(fullType)}  -> {file}");
    }
    Console.WriteLine($"{emitted.Count} message class(es) written to {Path.GetFullPath(outDir)}");
    return 0;
}
catch (Exception ex)
{
    Console.Error.WriteLine($"rosmsggen: {ex.Message}");
    return 1;
}

void Add(string file, string package)
{
    string fullType = $"{package}/{Path.GetFileNameWithoutExtension(file)}";
    sources[fullType] = File.ReadAllText(file);
}

// ROS layout: <package>/msg/<Name>.msg — the package is the directory above "msg".
static string PackageOf(string file)
{
    var dir = new DirectoryInfo(Path.GetDirectoryName(Path.GetFullPath(file))!);
    if (string.Equals(dir.Name, "msg", StringComparison.OrdinalIgnoreCase) && dir.Parent is not null)
        dir = dir.Parent;
    return dir.Name;
}
